/**
 * Generate docs/API-DIGEST.md from the compiler's own declaration output.
 *
 * Written by hand, this file was wrong within a day — it documented
 * `generateNeutralScale(seed, options)` when the real signature is
 * `(seed, tint, options)`, which silently passes an options object as a number.
 * A digest that can drift from the source is worse than no digest, so this one
 * is emitted by `tsc --emitDeclarationOnly` and is true by construction.
 *
 * Run: node scripts/gen-api-digest.mjs
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { basename, dirname, join, relative, resolve, sep } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const outDir = join(root, '.digest')
const configFile = join(root, 'tsconfig.digest.json')

const config = {
  compilerOptions: {
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'bundler',
    strict: true,
    skipLibCheck: true,
    declaration: true,
    emitDeclarationOnly: true,
    outDir: '.digest',
    baseUrl: '.',
    paths: { '@/*': ['./app/*'] },
    resolveJsonModule: true,
    types: [],
  },
  include: ['app/lib/**/*.ts'],
  // The two generated data modules are thousands of literals and tell a reader
  // nothing; their shape is documented by the module that consumes them.
  exclude: ['app/lib/**/*.spec.ts', 'app/lib/color/names.data.ts', 'app/lib/color/cvd.data.ts'],
}

writeFileSync(configFile, JSON.stringify(config, null, 2) + '\n')
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

try {
  execFileSync(process.execPath, [join(root, 'node_modules', 'typescript', 'lib', 'tsc.js'), '-p', configFile], {
    cwd: root,
    stdio: 'inherit',
  })
} finally {
  rmSync(configFile, { force: true })
}

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) out.push(...walk(full))
    else if (full.endsWith('.d.ts')) out.push(full)
  }
  return out
}

// Reading order matters more than alphabetical order: a reader wants the
// primitives before the things built on them.
const ORDER = [
  'types', 'spaces', 'convert', 'gamut', 'gradient', 'random', 'harmony',
  'scale', 'invert', 'alpha', 'contrast', 'cvd', 'name', 'extract', 'roles',
  'tokens', 'presets', 'url', 'document', 'config', 'graph', 'emitters',
  'password', 'api',
]

const files = walk(outDir).sort((a, b) => {
  const ra = ORDER.indexOf(basename(a, '.d.ts'))
  const rb = ORDER.indexOf(basename(b, '.d.ts'))
  return (ra < 0 ? 99 : ra) - (rb < 0 ? 99 : rb) || a.localeCompare(b)
})

let out =
  '# DevColorz — engine API\n\n' +
  'Generated from the compiler\'s own declaration output by\n' +
  '`node scripts/gen-api-digest.mjs`. Every signature here is what `tsc` sees.\n' +
  'Do not edit this file; edit the source and regenerate.\n\n'

for (const file of files) {
  const rel = relative(outDir, file).split(sep).join('/').replace(/\.d\.ts$/, '.ts')
  const body = readFileSync(file, 'utf8')
    .split('\n')
    .filter((line) => !line.startsWith('//'))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
  if (!body) continue
  out += `## \`${rel}\`\n\n\`\`\`ts\n${body}\n\`\`\`\n\n`
}

writeFileSync(join(root, 'docs', 'API-DIGEST.md'), out)
rmSync(outDir, { recursive: true, force: true })
if (existsSync(join(root, 'docs', 'API-DIGEST.md'))) {
  console.log(`docs/API-DIGEST.md — ${files.length} modules, ${(out.length / 1024).toFixed(1)} KB`)
}
