/**
 * Generates app/lib/color/names.data.ts from color-name-list.
 *
 * The upstream package is 19 MB unpacked; we only ship the "best of" subset,
 * packed as two flat strings so the runtime cost is a single lazy-loaded chunk
 * rather than 3,000 object literals.
 *
 * Run: node scripts/gen-color-names.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

const raw = JSON.parse(
  readFileSync(resolve(root, 'node_modules/color-name-list/dist/colornames.bestof.min.json'), 'utf8'),
)

const entries = Object.entries(raw)
  .filter(([hex, name]) => /^[0-9a-f]{6}$/i.test(hex) && typeof name === 'string' && name.length < 40)
  .sort((a, b) => a[0].localeCompare(b[0]))

const hexes = entries.map(([hex]) => hex.toLowerCase()).join('')
const names = entries.map(([, name]) => name).join('\n')

const out = `/* eslint-disable */
/**
 * Generated by scripts/gen-color-names.mjs — do not edit by hand.
 *
 * ${entries.length} curated color names from the color-name-list project
 * (https://github.com/meodai/color-names), packed flat: HEXES holds ${entries.length}
 * six-character hex codes back to back, NAMES holds the matching names
 * separated by newlines.
 */

export const COUNT = ${entries.length}

export const HEXES =
  ${JSON.stringify(hexes)}

export const NAMES =
  ${JSON.stringify(names)}
`

writeFileSync(resolve(root, 'app/lib/color/names.data.ts'), out)
console.log(`wrote ${entries.length} names, ${(out.length / 1024).toFixed(1)} KB`)
