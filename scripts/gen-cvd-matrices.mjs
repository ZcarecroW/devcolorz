/**
 * Extracts the Machado/Oliveira/Fernandes CVD matrices from culori's source
 * into a standalone data file.
 *
 * We cannot use culori's own filters: it multiplies the matrices against
 * gamma-encoded sRGB, but the published matrices are defined for LINEAR RGB.
 * Applying them to gamma-encoded values makes simulated colors noticeably too
 * light and shifts the hue. Owning the data lets us do it correctly.
 *
 * Run: node scripts/gen-cvd-matrices.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const src = readFileSync(resolve(root, 'node_modules/culori/src/deficiency.js'), 'utf8')

function extract(name) {
  const start = src.indexOf(`const ${name} = [`)
  if (start < 0) throw new Error(`missing ${name}`)
  let depth = 0
  let i = src.indexOf('[', start)
  const from = i
  for (; i < src.length; i++) {
    if (src[i] === '[') depth++
    else if (src[i] === ']') {
      depth--
      if (depth === 0) break
    }
  }
  const body = src.slice(from, i + 1)
  const rows = JSON.parse(body.replace(/(\d)\s*\n\s*/g, '$1').replace(/,\s*]/g, ']'))
  if (!Array.isArray(rows) || rows.some((r) => r.length !== 9)) {
    throw new Error(`${name}: expected rows of 9 values, got ${rows.map((r) => r.length)}`)
  }
  return rows
}

const data = { PROT: extract('PROT'), DEUTER: extract('DEUTER'), TRIT: extract('TRIT') }
const fmt = (rows) =>
  rows.map((r) => `  [${r.map((v) => String(v)).join(', ')}],`).join('\n')

const out = `/* eslint-disable */
/**
 * Generated by scripts/gen-cvd-matrices.mjs — do not edit by hand.
 *
 * Machado, Oliveira & Fernandes (2009), "A Physiologically-based Model for
 * Simulation of Color Vision Deficiency", IEEE TVCG 15(6), 1291-1298.
 * Precomputed matrices from https://www.inf.ufrgs.br/~oliveira/pubs_files/CVD_Simulation/
 *
 * Each table holds ${data.PROT.length} rows, one per severity step from 0.0 to 1.0 in
 * increments of 0.1. Each row is a row-major 3x3 matrix that must be applied to
 * LINEAR-light RGB, not to gamma-encoded sRGB.
 */

export type Matrix9 = readonly [number, number, number, number, number, number, number, number, number]

export const PROTAN: readonly Matrix9[] = [
${fmt(data.PROT)}
]

export const DEUTAN: readonly Matrix9[] = [
${fmt(data.DEUTER)}
]

export const TRITAN: readonly Matrix9[] = [
${fmt(data.TRIT)}
]
`
writeFileSync(resolve(root, 'app/lib/color/cvd.data.ts'), out)
console.log(`wrote ${data.PROT.length} severity steps per deficiency type`)
