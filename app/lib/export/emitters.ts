export const svgEmitter: Emitter = {
  id: 'svg',
  label: 'SVG swatch sheet',
  ext: 'svg',
  language: 'xml',
  hint: 'A vector contact sheet with hex labels — drop it into Figma or a slide deck.',
  emit(graph) {
    const tokens = graph.tokens.filter((t) => t.kind === 'base')
    const list = tokens.length ? tokens : graph.tokens
    const w = 160
    const h = 200
    // At least one cell: with every colour excluded the grid used to be zero
    // columns wide and its row count NaN, which no viewer opens.
    const columns = Math.max(1, Math.min(6, list.length))
    const rows = Math.max(1, Math.ceil(list.length / columns))
    let out = `<svg xmlns="http://www.w3.org/2000/svg" width="${columns * w}" height="${rows * h}" viewBox="0 0 ${columns * w} ${rows * h}" font-family="ui-sans-serif, system-ui, sans-serif">\n`
    out += `  <title>${xmlText(graph.title)}</title>\n`
    list.forEach((token, index) => {
      const x = (index % columns) * w
      const y = Math.floor(index / columns) * h
      const hex = formatColor(token.light, 'hex')
      // `apcaOnWhite` is high for a *dark* swatch, so the old test picked
      // near-black ink for near-black tiles and white for pale ones — every
      // label on the sheet was invisible. The engine already answers this.
      const ink = (bestBlackOrWhite(token.light).l ?? 0) > 0.5 ? '#ffffff' : '#111111'
      out += `  <g transform="translate(${x} ${y})">\n`
      out += `    <rect width="${w}" height="${h}" fill="${hex}"/>\n`
      out += `    <text x="16" y="${h - 34}" font-size="15" font-weight="600" fill="${ink}" font-family="ui-monospace, monospace">${hex.toUpperCase()}</text>\n`
      out += `    <text x="16" y="${h - 16}" font-size="11" fill="${ink}" opacity="0.75">${xmlText(token.name)}</text>\n`
      out += `  </g>\n`
    })
    out += '</svg>\n'
    return out
  },
}

