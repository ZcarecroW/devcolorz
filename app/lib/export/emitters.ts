export const gplEmitter: Emitter = {
  id: 'gpl',
  label: 'GIMP palette',
  ext: 'gpl',
  language: 'plaintext',
  hint: 'Opens in GIMP, Inkscape, Krita and Aseprite.',
  emit(graph) {
    let out = `GIMP Palette\nName: ${graph.title}\nColumns: ${Math.min(16, graph.tokens.length)}\n#\n`
    for (const token of graph.tokens) {
      const rgb = toRgb(token.light)
      const to255 = (v: number) => String(Math.round(Math.min(1, Math.max(0, v)) * 255)).padStart(3, ' ')
      out += `${to255(rgb.r)} ${to255(rgb.g)} ${to255(rgb.b)}\t${token.name}\n`
    }
    return out
  },
}

export const svgEmitter: Emitter = {
  id: 'svg',
  label: 'SVG swatch sheet',
  ext: 'svg',
  language: 'xml',
  hint: 'A vector contact sheet with hex labels — drop it into Figma or a slide deck.',
  emit(graph) {
    const tokens = graph.tokens.filter((t) => t.kind === 'base')
    const list = tokens.length ? tokens : graph.tokens
    const w = 160
    const h = 200
    const columns = Math.min(6, list.length)
    const rows = Math.ceil(list.length / columns)
    let out = `<svg xmlns="http://www.w3.org/2000/svg" width="${columns * w}" height="${rows * h}" viewBox="0 0 ${columns * w} ${rows * h}" font-family="ui-sans-serif, system-ui, sans-serif">\n`
    out += `  <title>${graph.title}</title>\n`
    list.forEach((token, index) => {
      const x = (index % columns) * w
      const y = Math.floor(index / columns) * h
      const hex = formatColor(token.light, 'hex')
      const ink = token.meta.apcaOnWhite > 45 ? '#111111' : '#ffffff'
      out += `  <g transform="translate(${x} ${y})">\n`
      out += `    <rect width="${w}" height="${h}" fill="${hex}"/>\n`
      out += `    <text x="16" y="${h - 34}" font-size="15" font-weight="600" fill="${ink}" font-family="ui-monospace, monospace">${hex.toUpperCase()}</text>\n`
      out += `    <text x="16" y="${h - 16}" font-size="11" fill="${ink}" opacity="0.75">${token.name}</text>\n`
      out += `  </g>\n`
    })
    out += '</svg>\n'
    return out
  },
}

