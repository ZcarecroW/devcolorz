export const cssEmitter: Emitter = {
  id: 'css',
  label: 'CSS custom properties',
  ext: 'css',
  language: 'css',
  hint: 'Plain custom properties on a selector of your choice. Works everywhere, in any framework or none.',
  emit(graph) {
    const { config } = graph
    let out = header(graph, (t) => `/* ${t} */`)
    out += `${config.selector} {\n${declarations(graph, 'light')}\n}\n`

    if (graph.hasDark) {
      const dark = declarations(graph, 'dark')
      const delivery = config.darkDelivery
      if (delivery === 'media' || delivery === 'both') {
        out += `\n@media (prefers-color-scheme: dark) {\n  ${config.selector} {\n${declarations(graph, 'dark', '    ')}\n  }\n}\n`
      }
      if (delivery === 'class' || delivery === 'both') {
        out += `\n${modeSelector(config, config.darkClass)} {\n${dark}\n}\n`
      }
      if (delivery === 'attribute') {
        out += `\n${modeSelector(config, config.darkAttribute)} {\n${dark}\n}\n`
      }
      if (delivery === 'both') {
        /*
         * The light override belongs *inside* the media query, and nowhere
         * else.
         *
         * A media query adds no specificity, so the dark rule above is a plain
         * `:root` at (0,1,0). The obvious light override — `:root:not(.dark)` —
         * is (0,2,0) and sits outside any media query, so it matched every
         * visitor who had not yet run a toggle script and beat the dark rule
         * unconditionally: the whole `@media` block was dead CSS and a dark-OS
         * visitor got the light palette, which is the exact flash this delivery
         * exists to prevent. Hard-coding `.dark` there made it worse — rename
         * the dark class and `:not(.dark)` matched even with the toggle applied,
         * so dark mode never rendered at all.
         *
         * Emitted last so that, at equal specificity, source order decides:
         * dark OS with no class wins on the media `:root`; dark OS with the
         * light class wins here; light OS with the dark class wins above.
         */
        out += `\n@media (prefers-color-scheme: dark) {\n  ${modeSelector(config, config.lightClass)} {\n${declarations(graph, 'light', '    ')}\n  }\n}\n`
      }
    }
    return out
  },
}

