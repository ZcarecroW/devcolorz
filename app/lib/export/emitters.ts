export const tailwind4Emitter: Emitter = {
  id: 'tailwind4',
  label: 'Tailwind CSS v4',
  ext: 'css',
  language: 'css',
  hint: 'A `@theme` block. Tailwind v4 reads its palette from CSS, so this is all it takes to get `bg-brand-500` and friends.',
  emit(graph) {
    const { config } = graph
    let out = header(graph, (t) => `/* ${t} */`)
    out += '@import "tailwindcss";\n\n'
    // Tailwind only generates utilities for variables under its own namespaces,
    // so the prefix has to be `--color-` regardless of what the user picked.
    out += '@theme {\n'
    for (const token of graph.tokens) {
      const name = token.name.replace(/^color-/, '')
      out += `  --color-${name}: ${value(token.light, config)};\n`
    }
    out += '}\n'

    if (graph.hasDark) {
      out += '\n@custom-variant dark (&:is(.dark *));\n'
      out += `\n${config.darkClass} {\n`
      for (const token of graph.tokens) {
        if (!token.dark) continue
        const name = token.name.replace(/^color-/, '')
        out += `  --color-${name}: ${value(token.dark, config)};\n`
      }
      out += '}\n'
    }
    return out
  },
}

export const tailwind3Emitter: Emitter = {
  id: 'tailwind3',
  label: 'Tailwind CSS v3 config',
  ext: 'js',
  language: 'javascript',
  hint: 'A `theme.extend.colors` object for `tailwind.config.js`.',
  emit(graph) {
    const { config } = graph
    // Group `brand-500` under `brand: { 500: … }` so the utilities read the way
    // Tailwind users expect.
    const tree: Record<string, string | Record<string, string>> = {}
    for (const token of graph.tokens) {
      const name = token.name.replace(new RegExp(`^${config.prefix}-?`), '')
      const match = /^(.*)-(\d{1,3}|a\d{1,3})$/.exec(name)
      if (match) {
        const [, stem, step] = match
        const bucket = (tree[stem] ??= {}) as Record<string, string>
        bucket[step] = value(token.light, config)
      } else {
        tree[name] = value(token.light, config)
      }
    }
    const body = JSON.stringify(tree, null, 2)
      .split('\n')
      .map((line, i) => (i === 0 ? line : `      ${line}`))
      .join('\n')
    return `${header(graph, (t) => `// ${t}`)}/** @type {import('tailwindcss').Config} */
export default {
  theme: {
    extend: {
      colors: ${body},
    },
  },
}
`
  },
}

