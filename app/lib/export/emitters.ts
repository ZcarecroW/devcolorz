/**
 * Output formats.
 *
 * Every emitter takes the same `TokenGraph` and returns text, so adding a
 * format cannot change which tokens exist — only how they are written down.
 */

import { formatColor, hexToken, toRgb } from '@/lib/color/convert'
import { wcagLevel } from '@/lib/color/contrast'
import type { Oklch } from '@/lib/color/types'
import type { ExportConfig } from './config'
import type { Token, TokenGraph } from './graph'

export interface Emitter {
  id: string
  label: string
  /** File extension, without the dot. */
  ext: string
  language: string
  /** One line explaining when to reach for this format. */
  hint: string
  emit(graph: TokenGraph): string
}

/* ------------------------------------------------------------------ *
 * Shared helpers
 * ------------------------------------------------------------------ */

function value(color: Oklch, config: ExportConfig): string {
  return formatColor(color, config.format, config.precision)
}

function header(graph: TokenGraph, comment: (text: string) => string): string {
  if (!graph.config.includeComments) return ''
  const lines = [
    `${graph.title} — generated by DevColorz`,
    `${graph.tokens.length} tokens${graph.hasDark ? ', light and dark' : ''}, ${graph.config.format} notation`,
  ]
  return lines.map(comment).join('\n') + '\n\n'
}

function contrastNote(token: Token, config: ExportConfig): string {
  if (!config.includeContrast) return token.comment ? ` /* ${token.comment} */` : ''
  const level = wcagLevel(token.meta.contrastOnWhite)
  const parts = [
    token.comment,
    `on white ${token.meta.contrastOnWhite.toFixed(2)}:1 (${level}), Lc ${token.meta.apcaOnWhite.toFixed(0)}`,
  ].filter(Boolean)
  return ` /* ${parts.join(' · ')} */`
}

/** Emit the tokens of one mode as CSS declarations. */
function declarations(graph: TokenGraph, mode: 'light' | 'dark', indent = '  '): string {
  const lines: string[] = []
  for (const token of graph.tokens) {
    const color = mode === 'light' ? token.light : token.dark
    if (!color) continue
    lines.push(`${indent}--${token.name}: ${value(color, graph.config)};${
      mode === 'light' ? contrastNote(token, graph.config) : ''
    }`)
  }
  return lines.join('\n')
}

