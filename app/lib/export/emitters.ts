export const dtcgEmitter: Emitter = {
  id: 'dtcg',
  label: 'Design Tokens (DTCG)',
  ext: 'tokens.json',
  language: 'json',
  hint: 'The W3C Design Tokens Community Group format, consumed by Style Dictionary, Tokens Studio and most token pipelines.',
  emit(graph) {
    const build = (mode: 'light' | 'dark') => {
      const group: Record<string, unknown> = {}
      for (const token of graph.tokens) {
        const color = mode === 'light' ? token.light : token.dark
        if (!color) continue
        const rgb = toRgb(color)
        group[token.name] = {
          $type: 'color',
          $value: {
            colorSpace: 'oklch',
            components: [
              Number((color.l ?? 0).toFixed(5)),
              Number((color.c ?? 0).toFixed(5)),
              Number((color.h ?? 0).toFixed(3)),
            ],
            alpha: color.alpha ?? 1,
            hex: `#${hexToken(rgb).toLowerCase()}`,
          },
          ...(token.comment ? { $description: token.comment } : {}),
          $extensions: {
            'org.devcolorz': {
              contrastOnWhite: Number(token.meta.contrastOnWhite.toFixed(3)),
              apcaOnWhite: Number(token.meta.apcaOnWhite.toFixed(1)),
              kind: token.kind,
            },
          },
        }
      }
      return group
    }
    const doc: Record<string, unknown> = {
      $description: `${graph.title} — generated by DevColorz`,
      color: build('light'),
    }
    if (graph.hasDark) doc.colorDark = build('dark')
    return JSON.stringify(doc, null, 2) + '\n'
  },
}

