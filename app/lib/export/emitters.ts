export const scssEmitter: Emitter = {
  id: 'scss',
  label: 'SCSS variables + map',
  ext: 'scss',
  language: 'scss',
  hint: 'Individual `$variables` plus a `$palette` map you can iterate with `@each`.',
  emit(graph) {
    const { config } = graph
    let out = header(graph, (t) => `// ${t}`)
    for (const token of graph.tokens) {
      out += `$${token.name}: ${value(token.light, config)};\n`
    }
    out += `\n$palette: (\n`
    out += graph.tokens.map((t) => `  '${t.name}': $${t.name},`).join('\n')
    out += `\n);\n`
    if (graph.hasDark) {
      out += `\n$palette-dark: (\n`
      out += graph.tokens
        .filter((t) => t.dark)
        .map((t) => `  '${t.name}': ${value(t.dark!, config)},`)
        .join('\n')
      out += `\n);\n`
    }
    return out
  },
}

