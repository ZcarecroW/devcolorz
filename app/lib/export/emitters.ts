export const tailwind4Emitter: Emitter = {
  id: 'tailwind4',
  label: 'Tailwind CSS v4',
  ext: 'css',
  language: 'css',
  hint: 'A `@theme` block. Tailwind v4 reads its palette from CSS, so this is all it takes to get `bg-brand-500` and friends.',
  emit(graph) {
    const { config } = graph
    let out = header(graph, (t) => `/* ${t} */`)
    out += '@import "tailwindcss";\n\n'
    // Tailwind only generates utilities for variables under its own namespaces,
    // so the prefix has to be `--color-` regardless of what the user picked.
    out += '@theme {\n'
    for (const token of graph.tokens) {
      out += `  --color-${tailwindName(token, config)}: ${value(token.light, config)};\n`
    }
    out += '}\n'

    if (graph.hasDark) {
      // The variant names the same class the values below are keyed on. A
      // literal `.dark` here left `dark:` utilities looking for a class the
      // user's own toggle never sets, once the class had been renamed.
      out += `\n@custom-variant dark (&:where(${config.darkClass}, ${config.darkClass} *));\n`
      out += `\n${config.darkClass} {\n`
      for (const token of graph.tokens) {
        if (!token.dark) continue
        out += `  --color-${tailwindName(token, config)}: ${value(token.dark, config)};\n`
      }
      out += '}\n'
    }
    return out
  },
}

export const tailwind3Emitter: Emitter = {
  id: 'tailwind3',
  label: 'Tailwind CSS v3 config',
  ext: 'js',
  language: 'javascript',
  hint: 'A `theme.extend.colors` object for `tailwind.config.js`. Keys are always kebab-case, because that is what the utility name is built from.',
  emit(graph) {
    const { config } = graph
    // Group `brand-500` under `brand: { 500: … }` so the utilities read the way
    // Tailwind users expect.
    const tree: Record<string, string | Record<string, string>> = {}
    for (const token of graph.tokens) {
      // `token.id` is already the un-prefixed, un-suffixed, collision-free
      // kebab stem, which is the shape a Tailwind config wants whatever the
      // configured case is. Building a RegExp out of the raw prefix instead
      // threw outright on a prefix containing a regex metacharacter, and
      // matched nothing at all in any case but kebab.
      const name = token.id
      const cut = token.kind === 'base' ? -1 : name.lastIndexOf('-')
      if (cut > 0) {
        const stem = name.slice(0, cut)
        const step = name.slice(cut + 1)
        // The bare colour may already be sitting on this key — `brand` before
        // `brand-500`. Tailwind's own convention for a bucket that also has a
        // value of its own is `DEFAULT`; assigning a step onto the string
        // threw instead, which broke the emitter for the nesting it exists for.
        const existing = tree[stem]
        const bucket = (typeof existing === 'string'
          ? (tree[stem] = { DEFAULT: existing })
          : (tree[stem] ??= {})) as Record<string, string>
        bucket[step] = value(token.light, config)
      } else {
        tree[name] = value(token.light, config)
      }
    }
    const body = JSON.stringify(tree, null, 2)
      .split('\n')
      .map((line, i) => (i === 0 ? line : `      ${line}`))
      .join('\n')
    return `${header(graph, (t) => `// ${t}`)}/** @type {import('tailwindcss').Config} */
export default {
  theme: {
    extend: {
      colors: ${body},
    },
  },
}
`
  },
}

