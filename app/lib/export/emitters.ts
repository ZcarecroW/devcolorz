export const cssEmitter: Emitter = {
  id: 'css',
  label: 'CSS custom properties',
  ext: 'css',
  language: 'css',
  hint: 'Plain custom properties on a selector of your choice. Works everywhere, in any framework or none.',
  emit(graph) {
    const { config } = graph
    let out = header(graph, (t) => `/* ${t} */`)
    out += `${config.selector} {\n${declarations(graph, 'light')}\n}\n`

    if (graph.hasDark) {
      const dark = declarations(graph, 'dark')
      const delivery = config.darkDelivery
      if (delivery === 'media' || delivery === 'both') {
        out += `\n@media (prefers-color-scheme: dark) {\n  ${config.selector} {\n${declarations(graph, 'dark', '    ')}\n  }\n}\n`
      }
      if (delivery === 'class' || delivery === 'both') {
        out += `\n${config.darkClass} {\n${dark}\n}\n`
      }
      if (delivery === 'attribute') {
        out += `\n${config.darkAttribute} {\n${dark}\n}\n`
      }
      if (delivery === 'both') {
        // The light override is what makes an in-page toggle work in both
        // directions: without it, a user on a dark OS cannot choose light.
        out += `\n:root:not(.dark), .light {\n${declarations(graph, 'light')}\n}\n`
      }
    }
    return out
  },
}

