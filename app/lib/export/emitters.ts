export const jsonEmitter: Emitter = {
  id: 'json',
  label: 'JSON',
  ext: 'json',
  language: 'json',
  hint: 'A flat object of name → value, with a `dark` block when dark variants are on.',
  emit(graph) {
    const { config } = graph
    const light: Record<string, string> = {}
    const dark: Record<string, string> = {}
    for (const token of graph.tokens) {
      light[token.name] = value(token.light, config)
      if (token.dark) dark[token.name] = value(token.dark, config)
    }
    return JSON.stringify(
      graph.hasDark ? { name: graph.title, light, dark } : { name: graph.title, ...light },
      null,
      2,
    ) + '\n'
  },
}

export const dtcgEmitter: Emitter = {
  id: 'dtcg',
  label: 'Design Tokens (DTCG)',
  ext: 'tokens.json',
  language: 'json',
  hint: 'The W3C Design Tokens Community Group format, consumed by Style Dictionary, Tokens Studio and most token pipelines.',
  emit(graph) {
    const { config } = graph
    const build = (mode: 'light' | 'dark') => {
      const group: Record<string, unknown> = {}
      for (const token of graph.tokens) {
        const color = mode === 'light' ? token.light : token.dark
        if (!color) continue
        const rgb = toRgb(color)
        group[token.name] = {
          $type: 'color',
          $value: {
            colorSpace: 'oklch',
            components: [
              Number((color.l ?? 0).toFixed(5)),
              Number((color.c ?? 0).toFixed(5)),
              Number((color.h ?? 0).toFixed(3)),
            ],
            alpha: color.alpha ?? 1,
            hex: `#${hexToken(rgb).toLowerCase()}`,
          },
          ...(token.comment ? { $description: token.comment } : {}),
          $extensions: {
            'vision.fabula.devcolorz': {
              contrastOnWhite: Number(token.meta.contrastOnWhite.toFixed(3)),
              apcaOnWhite: Number(token.meta.apcaOnWhite.toFixed(1)),
              kind: token.kind,
            },
          },
        }
      }
      return group
    }
    const doc: Record<string, unknown> = {
      $description: `${graph.title} — generated by DevColorz`,
      color: build('light'),
    }
    if (graph.hasDark) doc.colorDark = build('dark')
    return JSON.stringify(doc, null, 2) + '\n'
  },
}

export const tsEmitter: Emitter = {
  id: 'ts',
  label: 'TypeScript',
  ext: 'ts',
  language: 'typescript',
  hint: 'A `const` object with a literal type, so consumers get autocomplete on token names.',
  emit(graph) {
    const { config } = graph
    const entries = graph.tokens
      .map((t) => `  '${t.name}': '${value(t.light, config)}',`)
      .join('\n')
    let out = header(graph, (t) => `// ${t}`)
    out += `export const palette = {\n${entries}\n} as const\n\n`
    out += `export type PaletteToken = keyof typeof palette\n`
    if (graph.hasDark) {
      const darkEntries = graph.tokens
        .filter((t) => t.dark)
        .map((t) => `  '${t.name}': '${value(t.dark!, config)}',`)
        .join('\n')
      out += `\nexport const paletteDark = {\n${darkEntries}\n} as const satisfies Partial<Record<PaletteToken, string>>\n`
    }
    return out
  },
}

export const csvEmitter: Emitter = {
  id: 'csv',
  label: 'CSV',
  ext: 'csv',
  language: 'plaintext',
  hint: 'One row per token, with hex, OKLCH channels and both contrast metrics — handy for a spreadsheet audit.',
  emit(graph) {
    const rows = [
      'name,kind,hex,oklch,l,c,h,contrast_on_white,contrast_on_black,apca_on_white,apca_on_black,wcag_level_on_white',
    ]
    for (const token of graph.tokens) {
      const c = token.light
      rows.push(
        [
          token.name,
          token.kind,
          formatColor(c, 'hex'),
          formatColor(c, 'oklch'),
          (c.l ?? 0).toFixed(4),
          (c.c ?? 0).toFixed(4),
          (c.h ?? 0).toFixed(2),
          token.meta.contrastOnWhite.toFixed(3),
          token.meta.contrastOnBlack.toFixed(3),
          token.meta.apcaOnWhite.toFixed(1),
          token.meta.apcaOnBlack.toFixed(1),
          wcagLevel(token.meta.contrastOnWhite),
        ].join(','),
      )
    }
    return rows.join('\n') + '\n'
  },
}

