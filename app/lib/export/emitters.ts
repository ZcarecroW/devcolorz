export const androidEmitter: Emitter = {
  id: 'android',
  label: 'Android colors.xml',
  ext: 'xml',
  language: 'xml',
  hint: 'Drop into `res/values/`. Dark values belong in `res/values-night/colors.xml`.',
  emit(graph) {
    const name = (t: Token) => t.name.replace(/-/g, '_')
    const argb = (color: Oklch) => {
      const rgb = toRgb(color)
      const a = Math.round((color.alpha ?? 1) * 255)
      const hex = hexToken(rgb)
      return `#${a === 255 ? '' : a.toString(16).padStart(2, '0').toUpperCase()}${hex}`
    }
    let out = '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
    for (const token of graph.tokens) {
      out += `    <color name="${name(token)}">${argb(token.light)}</color>\n`
    }
    out += '</resources>\n'
    if (graph.hasDark) {
      out += '\n<!-- res/values-night/colors.xml -->\n<resources>\n'
      for (const token of graph.tokens) {
        if (!token.dark) continue
        out += `    <color name="${name(token)}">${argb(token.dark)}</color>\n`
      }
      out += '</resources>\n'
    }
    return out
  },
}

export const swiftEmitter: Emitter = {
  id: 'swift',
  label: 'SwiftUI',
  ext: 'swift',
  language: 'swift',
  hint: 'A `Color` extension. Uses the Display P3 initialiser so wide-gamut colours survive on Apple hardware.',
  emit(graph) {
    const camel = (name: string) =>
      name
        .split('-')
        .map((part, i) => (i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)))
        .join('')
    let out = header(graph, (t) => `// ${t}`)
    out += 'import SwiftUI\n\npublic extension Color {\n'
    for (const token of graph.tokens) {
      const rgb = toRgb(token.light)
      const f = (v: number) => Math.min(1, Math.max(0, v)).toFixed(4)
      out += `    static let ${camel(token.name)} = Color(.displayP3, red: ${f(rgb.r)}, green: ${f(rgb.g)}, blue: ${f(rgb.b)}, opacity: ${(token.light.alpha ?? 1).toFixed(3)})\n`
    }
    out += '}\n'
    return out
  },
}

