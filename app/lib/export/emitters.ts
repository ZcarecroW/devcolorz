/**
 * Output formats.
 *
 * Every emitter takes the same `TokenGraph` and returns text, so adding a
 * format cannot change which tokens exist — only how they are written down.
 */

import { formatColor, hexToken, toRgb } from '@/lib/color/convert'
import { bestBlackOrWhite, wcagLevel } from '@/lib/color/contrast'
import type { Oklch } from '@/lib/color/types'
import type { ExportConfig } from './config'
import { composeName, type Token, type TokenGraph } from './graph'

export interface EmittedFile {
  /** Path relative to the project, as the platform expects it. */
  path: string
  content: string
}

export interface Emitter {
  id: string
  label: string
  /** File extension, without the dot. */
  ext: string
  language: string
  /** One line explaining when to reach for this format. */
  hint: string
  /** The output as one readable text, for the panel and the clipboard. */
  emit(graph: TokenGraph): string
  /**
   * The output as the files it actually has to be split into, for downloads.
   * Only formats whose target cannot take one file define this — Android
   * keeps day and night values in two files that are each one XML document,
   * and saved as a single file the pair is not well-formed.
   */
  files?(graph: TokenGraph): EmittedFile[]
}

/**
 * The files an emitter produces, for a format that needs more than one.
 *
 * The default download is the single text `emit` returns, under the emitter's
 * own extension.
 */
export function emittedFiles(emitter: Emitter, graph: TokenGraph, stem: string): EmittedFile[] {
  return emitter.files?.(graph) ?? [{ path: `${stem}.${emitter.ext}`, content: emitter.emit(graph) }]
}

/* ------------------------------------------------------------------ *
 * Shared helpers
 * ------------------------------------------------------------------ */

/** Escape text going into an XML/SVG text node. */
const xmlText = (text: string): string =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

/**
 * Make user text safe inside a comment.
 *
 * The palette title and a swatch's name are free text, and a title carrying a
 * comment terminator closes a CSS block comment early — corrupting every rule
 * after it. A newline does the same to the line comments the JavaScript
 * emitters use.
 */
const safeComment = (text: string): string =>
  text
    .replace(/\*\/|\/\*/g, ' ')
    .replace(/[\r\n]+/g, ' ')
    .trim()

/**
 * The name Tailwind should see.
 *
 * Tailwind reads utilities off `--color-*`, so this file is kebab whatever the
 * configured case is — but the user's prefix and suffix still belong in it.
 * Stripping a hard-coded `color-` off the *rendered* name only worked in
 * kebab: with camelCase the name was `colorBrand`, the strip missed, and every
 * variable came out as `--color-colorBrand`.
 */
function tailwindName(token: Token, config: ExportConfig): string {
  return composeName({ ...config, case: 'kebab' }, token.id).replace(/^color-/, '')
}

function value(color: Oklch, config: ExportConfig): string {
  return formatColor(color, config.format, config.precision)
}

function header(graph: TokenGraph, comment: (text: string) => string): string {
  if (!graph.config.includeComments) return ''
  const lines = [
    `${safeComment(graph.title)} — generated by DevColorz`,
    `${graph.tokens.length} tokens${graph.hasDark ? ', light and dark' : ''}, ${graph.config.format} notation`,
  ]
  return lines.map(comment).join('\n') + '\n\n'
}

/**
 * The note that follows a declaration.
 *
 * Two independent switches, so both are checked. Turning Comments off used to
 * drop the header and leave the per-token provenance note on every line — in a
 * palette with scales, a hundred-odd comments in a file the user had just
 * asked to have none.
 */
function contrastNote(token: Token, config: ExportConfig): string {
  const note = config.includeComments && token.comment ? safeComment(token.comment) : ''
  if (!config.includeContrast) return note ? ` /* ${note} */` : ''
  const level = wcagLevel(token.meta.contrastOnWhite)
  const parts = [
    note,
    `on white ${token.meta.contrastOnWhite.toFixed(2)}:1 (${level}), Lc ${token.meta.apcaOnWhite.toFixed(0)}`,
  ].filter(Boolean)
  return ` /* ${parts.join(' · ')} */`
}

/**
 * The selector for a mode override.
 *
 * `.dark` on its own only outranks the base rule when that rule is a single
 * class or pseudo-class — `:root`, the default. Against `#app` or `.theme` it
 * loses on specificity whatever the source order, and the whole override is
 * dead CSS. For any other base selector the mode class is paired with it, on
 * the same element and as an ancestor: `.dark#app, .dark #app` outranks
 * `#app` wherever a toggle script is likely to put the class.
 */
function modeSelector(config: ExportConfig, modeClass: string): string {
  const base = config.selector.trim()
  if (/^(:root|html|body)$/i.test(base)) return modeClass
  // Only a class, id, attribute or pseudo-class can follow another selector
  // without a space; `html.theme` would otherwise become `.darkhtml.theme`.
  const compound = /^[.#[:]/.test(base) ? `${modeClass}${base}, ` : ''
  return `${compound}${modeClass} ${base}`
}

/** Emit the tokens of one mode as CSS declarations. */
function declarations(graph: TokenGraph, mode: 'light' | 'dark', indent = '  '): string {
  const lines: string[] = []
  for (const token of graph.tokens) {
    const color = mode === 'light' ? token.light : token.dark
    if (!color) continue
    lines.push(`${indent}--${token.name}: ${value(color, graph.config)};${
      mode === 'light' ? contrastNote(token, graph.config) : ''
    }`)
  }
  return lines.join('\n')
}

